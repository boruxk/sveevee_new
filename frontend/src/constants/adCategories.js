export const AD_CATEGORY_SELECT_OPTIONS = AD_CATEGORY_GROUPS.flatMap((group) => [
	{
		label: group.label,
		value: `${group.key}.__group`,
		disable: true,
		group: true,
		color: group.color
	},
	...group.items.map(([itemKey, label]) => ({
		label,
		value: `${group.key}.${itemKey}`,
		itemKey,
		groupKey: group.key,
		groupLabel: group.label,
		color: group.color,
		soft: group.soft
	}))
])

const AD_CATEGORY_META = new Map(
	AD_CATEGORY_SELECT_OPTIONS
		.filter((option) => !option.group)
		.map((option) => [option.value, option])
)

export function adCategoryMeta(category) {
	return AD_CATEGORY_META.get(category) || null
}

function translated(t, key, fallback) {
	const value = t(key)

	return value === key ? fallback : value
}

export function localizedAdCategoryMeta(category, t) {
	const meta = adCategoryMeta(category)

	if (!meta) {
		return null
	}

	return {
		...meta,
		label: translated(t, `adCategories.items.${meta.groupKey}.${meta.itemKey}`, meta.label),
		groupLabel: translated(t, `adCategories.groups.${meta.groupKey}`, meta.groupLabel)
	}
}
